#include "loadingScreen.hpp"
#include "../../audio/loadingsfx/loadingSound.hpp"

#include <iostream>
#include <chrono>
#include <thread>

void loadingScreen() {

    const char* frames[] = {
        "[=                                ]",
        "[==                               ]",
        "[===                              ]",
        "[====                             ]",
        "[=====                            ]",
        "[======                           ]",
        "[=======                          ]",
        "[========                         ]",
        "[=========                        ]",
        "[==========                       ]",
        "[==========                       ]",
        "[===========                      ]",
        "[============                     ]",
        "[=============                    ]",
        "[==============                   ]",
        "[===============                  ]",
        "[================                 ]",
        "[=================                ]",
        "[==================               ]",
        "[===================              ]",
        "[====================             ]",
        "[=====================            ]",
        "[======================           ]",
        "[=======================          ]",
        "[========================         ]",
        "[=========================        ]",
        "[==========================       ]",
        "[===========================      ]",
        "[============================     ]",
        "[=============================    ]",
        "[==============================   ]",
        "[===============================  ]",
        "[================================ ]",
        "[=================================]"
    };


    for (int i = 0; i < 34; i++) {

        std::cout
            << "\r"
            << frames[i]
            << std::flush;


        // Play sound every frames
            loadingTickSound();


        std::this_thread::sleep_for(
            std::chrono::milliseconds(50)
        );
    }


    std::cout << '\n';


    // Finished loading
    loadingCompleteSound();
}