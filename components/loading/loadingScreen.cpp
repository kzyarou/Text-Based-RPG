#include "loadingScreen.hpp"
#include <iostream>
#include <chrono>
#include <thread>

void loadingScreen() {
    const char* frames[]  = {
        "[=                                ]",
        "[==                               ]",
        "[===                              ]",
        "[====                             ]",
        "[=====                            ]",
        "[======                           ]",
        "[=======                          ]",
        "[========                         ]",
        "[=========                        ]",
        "[==========                       ]",
        "[==========                       ]",
        "[===========                      ]",
        "[============                     ]",
        "[=============                    ]",
        "[==============                   ]",
        "[===============                  ]",
        "[================                 ]",
        "[=================                ]",
        "[==================               ]",
        "[===================              ]",
        "[====================             ]",
        "[=====================            ]",
        "[======================           ]",
        "[=======================          ]",
        "[========================         ]",
        "[=========================        ]",
        "[==========================       ]",
        "[===========================      ]",
        "[============================     ]",
        "[=============================    ]",
        "[==============================   ]",
        "[===============================  ]",
        "[================================ ]",
        "[=================================]",
    };

    for (const char* frame : frames) {
        std::cout << "\r" << frame << std::flush;
        std::this_thread::sleep_for(std::chrono::milliseconds(50));
    }

    std::cout << '\n';
}